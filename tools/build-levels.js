#!/usr/bin/env node
'use strict';
/*
 * Concatenate levels/src/chNN.json into js/levels.js (UMD; browser: WB.CHAPTERS
 * and WB.LEVELS, Node: module.exports = { chapters, levels }).
 *
 *   node tools/build-levels.js [--src dir] [--out file] [--check] [--quiet]
 *
 * Every level is validated with WB.validateLevel first; nothing is written if
 * any level (or chapter file) has errors. --check writes nothing and exits 1
 * when the output file is not up to date.
 */

const fs = require('fs');
const path = require('path');
const lib = require('./lib');
const WB = lib.WB;

const HEADER = '/* Generated by tools/build-levels.js from levels/src/*.json. Do not edit by hand. */';
const WRAP = 100; // wrap piece lists longer than this

/** JSON with spaces, on one line: { "a": 1, "b": [1, 2] }. */
function inline(v) {
  if (Array.isArray(v)) return '[' + v.map(inline).join(', ') + ']';
  if (v && typeof v === 'object') {
    const keys = Object.keys(v);
    if (!keys.length) return '{}';
    return '{ ' + keys.map((k) => JSON.stringify(k) + ': ' + inline(v[k])).join(', ') + ' }';
  }
  return JSON.stringify(v);
}

function normInventory(inv) {
  const out = {};
  const keys = WB.TOOL_ORDER.filter((k) => inv && inv[k] > 0);
  for (const k of keys) out[k] = inv[k];
  return out;
}

/** Level as stored in js/levels.js (fixed key order, normalised pieces). */
function normLevel(def, n, chapter) {
  const out = { id: n, chapter, name: def.name || '' };
  if (def.tip) out.tip = def.tip;
  const wind = def.wind || {};
  out.wind = { from: wind.from != null ? String(wind.from).toUpperCase() : 'W', strength: wind.strength | 0 };
  out.map = def.map.slice();
  out.fixed = (def.fixed || []).map(lib.cleanPiece);
  out.inventory = normInventory(def.inventory);
  out.solution = (def.solution || []).map(lib.cleanPiece);
  return out;
}

/** Load + validate everything. Returns { data, errors, warnings }. */
function collect(srcDir) {
  const { chapters, problems, levels } = lib.loadAllLevels(srcDir);
  const errors = problems.filter((p) => p.severity === 'error').map((p) => p.msg);
  const warnings = problems.filter((p) => p.severity === 'warn').map((p) => p.msg);
  const data = { chapters: [], levels: [] };
  const present = [];
  for (const ch of chapters) {
    if (ch.chapter == null || ch.single || !ch.levels.length) continue;
    const count = Math.min(ch.levels.length, lib.LEVELS_PER_CHAPTER);
    const first = lib.levelNumber(ch.chapter, 0);
    data.chapters.push({
      n: ch.chapter,
      title: ch.title || '',
      tool: ch.chapter <= WB.TOOL_ORDER.length ? WB.TOOL_ORDER[ch.chapter - 1] : null,
      first,
      last: first + count - 1
    });
    present.push(ch.chapter);
  }
  for (let c = 1; present.length && c < present[present.length - 1]; c++) {
    if (!present.includes(c)) warnings.push('chapter ' + c + ' is missing (level numbers will have a gap)');
  }
  for (const e of levels) {
    const where = path.basename(e.file) + '[' + e.index + '] #' + e.n + ' "' + ((e.def && e.def.name) || '') + '"';
    const errs = WB.validateLevel(e.def);
    if (!e.def || typeof e.def !== 'object' || !e.def.name) errs.push('level has no name');
    if (errs.length) { errors.push(...errs.map((m) => where + ': ' + m)); continue; }
    data.levels.push(normLevel(e.def, e.n, e.chapter));
  }
  if (!data.levels.length && !errors.length) errors.push('no levels found in ' + (srcDir || lib.SRC_DIR));
  return { data, errors, warnings };
}

function formatPieces(list, indent) {
  const one = inline(list);
  if (one.length <= WRAP) return one;
  return '[\n' + list.map((p) => indent + '  ' + inline(p)).join(',\n') + '\n' + indent + ']';
}

function formatLevel(L) {
  const I = '      ';
  const lines = [];
  lines.push(I + '"id": ' + L.id + ', "chapter": ' + L.chapter + ', "name": ' + JSON.stringify(L.name) + ',');
  if (L.tip) lines.push(I + '"tip": ' + JSON.stringify(L.tip) + ',');
  lines.push(I + '"wind": ' + inline(L.wind) + ',');
  lines.push(I + '"map": [\n' + L.map.map((r) => I + '  ' + JSON.stringify(r)).join(',\n') + '\n' + I + '],');
  lines.push(I + '"fixed": ' + formatPieces(L.fixed, I) + ',');
  lines.push(I + '"inventory": ' + inline(L.inventory) + ',');
  lines.push(I + '"solution": ' + formatPieces(L.solution, I));
  return '    {\n' + lines.join('\n') + '\n    }';
}

function format(data) {
  return HEADER + '\n' +
    '(function (root) {\n' +
    '  var data = {\n' +
    '  "chapters": [\n' +
    data.chapters.map((c) => '    ' + inline(c)).join(',\n') + '\n' +
    '  ],\n' +
    '  "levels": [\n' +
    data.levels.map(formatLevel).join(',\n') + '\n' +
    '  ]\n' +
    '};\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = data;\n" +
    '  else { root.WB = root.WB || {}; root.WB.CHAPTERS = data.chapters; root.WB.LEVELS = data.levels; }\n' +
    "})(typeof self !== 'undefined' ? self : this);\n";
}

/** Build; returns { ok, out, text, errors, warnings, written, upToDate }. */
function build(opts) {
  opts = opts || {};
  const out = path.resolve(opts.out || path.join(lib.ROOT, 'js', 'levels.js'));
  const { data, errors, warnings } = collect(opts.src);
  const res = { ok: !errors.length, out, errors, warnings, data, written: false, upToDate: false, text: null };
  if (errors.length) return res;
  res.text = format(data);
  let old = null;
  try { old = fs.readFileSync(out, 'utf8'); } catch (e) { /* missing */ }
  res.upToDate = old === res.text;
  if (!opts.check && !res.upToDate) {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, res.text);
    res.written = true;
  }
  return res;
}

const USAGE = `usage: node tools/build-levels.js [--src dir] [--out file] [--check] [--quiet]
  --src dir    chapter directory (default levels/src)
  --out file   output (default js/levels.js)
  --check      do not write; exit 1 if the output is out of date
  --quiet      only print errors`;

function main(argv) {
  const a = lib.parseArgs(argv, { values: ['src', 'out'], bools: ['check', 'quiet'] });
  if (a.flags.help) { console.log(USAGE); return 0; }
  if (a._.length) throw new Error('unexpected argument ' + a._[0] + '\n' + USAGE);
  const res = build({ src: a.flags.src, out: a.flags.out, check: a.flags.check });
  let rel = path.relative(process.cwd(), res.out) || res.out;
  if (rel.startsWith('..')) rel = res.out;
  if (!a.flags.quiet) for (const w of res.warnings) console.log('warn: ' + w);
  if (!res.ok) {
    for (const e of res.errors) console.error('error: ' + e);
    console.error('build failed: ' + res.errors.length + ' error(s); ' + rel + ' not written');
    return 1;
  }
  const what = res.data.levels.length + ' levels in ' + res.data.chapters.length + ' chapter(s)';
  if (a.flags.check) {
    console.log(res.upToDate ? rel + ' is up to date (' + what + ')' : rel + ' is OUT OF DATE; run npm run build');
    return res.upToDate ? 0 : 1;
  }
  if (!a.flags.quiet) console.log((res.written ? 'wrote ' : 'unchanged ') + rel + ': ' + what);
  return 0;
}

module.exports = { build, collect, format, normLevel, inline, HEADER };

if (require.main === module) lib.runCli(main);
